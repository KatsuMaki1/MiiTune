"""Generates assets/icons_atlas.png (the icon sheet) and src/icons_ids.h from assets/lucide/*.svg.
Icons: Lucide (https://lucide.dev, ISC license). Usage: python tools/gen_icons.py  (needs pymupdf + pillow)."""
import io, os, re, sys
import pymupdf
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SVG_DIR = os.path.join(ROOT, 'assets', 'lucide')
CELL, COLS = 96, 8

# (C++ identifier, lucide file, filled?)
ICONS = [
    ('HOUSE', 'house', False), ('SEARCH', 'search', False), ('MUSIC', 'music', False),
    ('LIST_MUSIC', 'list-music', False), ('USER_ROUND', 'user-round', False), ('SETTINGS', 'settings', False),
    ('SHUFFLE', 'shuffle', False), ('SKIP_BACK', 'skip-back', True), ('SKIP_FORWARD', 'skip-forward', True),
    ('ROTATE_CCW', 'rotate-ccw', False), ('ROTATE_CW', 'rotate-cw', False),
    ('PLAY', 'play', True), ('PAUSE', 'pause', True), ('REPEAT', 'repeat', False), ('REPEAT_1', 'repeat-1', False),
    ('HEART', 'heart', False), ('HEART_FILLED', 'heart', True), ('MOON', 'moon', False), ('PLUS', 'plus', False),
    ('MIC_VOCAL', 'mic-vocal', False), ('USER', 'user', False), ('VOLUME_2', 'volume-2', False),
    ('ARROW_LEFT', 'arrow-left', False), ('X', 'x', False), ('CHEVRON_UP', 'chevron-up', False),
    ('RADIO', 'radio', False), ('LIST_PLUS', 'list-plus', False), ('LIST_END', 'list-end', False),
    ('TRASH_2', 'trash-2', False), ('DISC_3', 'disc-3', False), ('CLOCK', 'clock', False),
]

rows = (len(ICONS) + COLS - 1) // COLS
atlas = Image.new('RGBA', (COLS * CELL, rows * CELL), (255, 255, 255, 0))
for i, (cid, name, filled) in enumerate(ICONS):
    svg = open(os.path.join(SVG_DIR, name + '.svg'), encoding='utf-8').read()
    svg = svg.replace('stroke="currentColor"', 'stroke="#ffffff"')
    if filled:
        svg = svg.replace('fill="none"', 'fill="#ffffff"', 1)
    doc = pymupdf.open(stream=svg.encode('utf-8'), filetype='svg')
    page = doc[0]
    scale = CELL / page.rect.width
    pix = page.get_pixmap(matrix=pymupdf.Matrix(scale, scale), alpha=True)
    im = Image.open(io.BytesIO(pix.tobytes('png'))).convert('RGBA')
    im = im.resize((CELL, CELL), Image.LANCZOS)
    alpha = im.getchannel('A')
    white = Image.new('RGBA', im.size, (255, 255, 255, 255))
    white.putalpha(alpha)           # pure white + alpha: the colour is applied at draw time
    atlas.paste(white, ((i % COLS) * CELL, (i // COLS) * CELL))

buf = io.BytesIO()
atlas.save(buf, format='PNG', optimize=True)
data = buf.getvalue()
atlas.save(os.path.join(ROOT, 'assets', 'icons_atlas.png'))

with open(os.path.join(ROOT, 'src', 'icons_ids.h'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/gen_icons.py - DO NOT EDIT\n#pragma once\n')
    f.write('constexpr int ICON_CELL = %d, ICON_COLS = %d;\nenum IconId {\n' % (CELL, COLS))
    for cid, _, _ in ICONS:
        f.write('    IC_%s,\n' % cid)
    f.write('    IC_COUNT\n};\n')
print('atlas', atlas.size, len(data), 'bytes,', len(ICONS), 'icons')
